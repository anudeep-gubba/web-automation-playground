import '@testing-library/jest-dom/vitest'

// jsdom does not implement matchMedia; ThemeProvider relies on it to resolve
// the "system" theme preference.
if (typeof window !== 'undefined' && !window.matchMedia) {
  window.matchMedia = (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  })
}

